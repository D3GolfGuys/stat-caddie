/* Stat Caddie — client-side PDF reports
 * ------------------------------------------------------------------
 * One-click, real .pdf downloads generated in the browser with jsPDF +
 * jspdf-autotable (loaded from CDN). No server load. Two reports:
 *   StatCaddiePDF.playerReport({ playerName, teamName, rounds })
 *   StatCaddiePDF.teamReport({ teamName, players, rounds })
 * `rounds` are round objects that each carry a `.summary` (the same JSON the
 * capture page computes and the dashboard reads). Season figures are aggregated
 * here — counts summed, rates re-derived from raw hits/attempts where possible.
 */
(function () {
  const C = {
    dark: [26, 58, 42], mid: [45, 92, 62], gold: [184, 134, 11],
    muted: [110, 124, 115], line: [200, 210, 200],
  };

  // formatters
  const f1  = v => (v == null || isNaN(v)) ? '—' : (Math.round(v * 10) / 10).toFixed(1);
  const pct = v => (v == null || isNaN(v)) ? '—' : (Math.round(v * 10) / 10).toFixed(1) + '%';
  const vs  = v => { if (v == null || isNaN(v)) return '—'; const r = Math.round(v * 10) / 10; return r === 0 ? 'E' : (r > 0 ? '+' + r : '' + r); };
  const num = v => (v == null || isNaN(v)) ? '—' : ('' + v);

  const avg = (arr, k) => { const v = arr.filter(s => s && s[k] != null); return v.length ? v.reduce((a, b) => a + b[k], 0) / v.length : null; };
  const sum = (arr, k) => { let t = 0, any = false; arr.forEach(s => { if (s && s[k] != null) { t += s[k]; any = true; } }); return any ? t : null; };
  const maxOf = (arr, k) => { let m = null; arr.forEach(s => { if (s && s[k] != null) m = (m == null ? s[k] : Math.max(m, s[k])); }); return m; };

  function computeSeason(rounds) {
    const sums = rounds.map(r => r.summary).filter(Boolean);
    const fwHit = sum(sums, 'fwHit'), fwAtt = sum(sums, 'fwAtt');
    const girHit = sum(sums, 'girHit'), girHoles = 18 * sums.length;
    const udAtt = sum(sums, 'udAtt'), udMade = sum(sums, 'udMade');
    const ssAtt = sum(sums, 'ssAtt'), ssMade = sum(sums, 'ssMade');
    const scores = sums.map(s => s.totalScore).filter(v => v != null);
    return {
      rounds: rounds.length, statted: sums.length,
      scoringAvg: avg(sums, 'totalScore'), vspar: avg(sums, 'vspar'),
      best: scores.length ? Math.min.apply(null, scores) : null,
      fwPct: fwAtt ? fwHit / fwAtt * 100 : avg(sums, 'fwPct'), fwHit, fwAtt,
      girPct: girHoles ? girHit / girHoles * 100 : avg(sums, 'girPct'), girHit, girHoles,
      driveAvg: avg(sums, 'driveAvg'), driveMax: maxOf(sums, 'driveMax'),
      proxAvg: avg(sums, 'proxAvg'), proxGir: avg(sums, 'proxGirAvg'), proxMiss: avg(sums, 'proxMissAvg'),
      puttsPerRound: avg(sums, 'puttsTotal'), puttsPerGir: avg(sums, 'puttsPerGir'),
      onePutts: sum(sums, 'onePutts'), threePutts: sum(sums, 'threePutts'),
      scramblingPct: udAtt ? udMade / udAtt * 100 : null, udAtt, udMade,
      ssPct: ssAtt ? ssMade / ssAtt * 100 : null, ssAtt, ssMade,
      penTotal: sum(sums, 'penTotal'),
      eagles: sum(sums, 'eagles'), birdies: sum(sums, 'birdies'), pars: sum(sums, 'pars'),
      bogeys: sum(sums, 'bogeys'), doubles: sum(sums, 'doubles'), worses: sum(sums, 'worses'),
      par3Avg: avg(sums, 'par3Avg'), par4Avg: avg(sums, 'par4Avg'), par5Avg: avg(sums, 'par5Avg'),
      par3GirPct: avg(sums, 'par3GirPct'), par4GirPct: avg(sums, 'par4GirPct'), par5GirPct: avg(sums, 'par5GirPct'),
    };
  }

  // ── shared drawing helpers ───────────────────────────────────────
  function ensureLib() {
    if (!window.jspdf || !window.jspdf.jsPDF) {
      alert('The PDF library did not load (check your connection) — please retry.');
      return null;
    }
    return window.jspdf.jsPDF;
  }
  function header(doc, kicker) {
    const W = doc.internal.pageSize.getWidth();
    doc.setFillColor.apply(doc, C.dark); doc.rect(0, 0, W, 54, 'F');
    doc.setTextColor(255, 255, 255);
    doc.setFont('helvetica', 'bold'); doc.setFontSize(15); doc.text('STAT CADDIE', 40, 32);
    doc.setFont('helvetica', 'normal'); doc.setFontSize(9); doc.setTextColor(200, 220, 205);
    doc.text(kicker.toUpperCase(), W - 40, 32, { align: 'right' });
  }
  function footer(doc) {
    const W = doc.internal.pageSize.getWidth(), H = doc.internal.pageSize.getHeight();
    doc.setDrawColor.apply(doc, C.line); doc.setLineWidth(0.5); doc.line(40, H - 30, W - 40, H - 30);
    doc.setFont('helvetica', 'normal'); doc.setFontSize(8); doc.setTextColor.apply(doc, C.muted);
    doc.text('Generated by Stat Caddie', 40, H - 18);
    try { doc.text(new Date().toLocaleDateString(), W - 40, H - 18, { align: 'right' }); } catch (e) {}
  }
  function kpiRow(doc, y, items) {
    const W = doc.internal.pageSize.getWidth(), m = 40, gap = 8;
    const w = (W - 2 * m - gap * (items.length - 1)) / items.length;
    items.forEach((it, i) => {
      const x = m + i * (w + gap);
      doc.setDrawColor.apply(doc, C.line); doc.setFillColor(246, 250, 246);
      doc.roundedRect(x, y, w, 42, 4, 4, 'FD');
      doc.setTextColor.apply(doc, C.dark); doc.setFont('helvetica', 'bold'); doc.setFontSize(14);
      doc.text(String(it.val), x + w / 2, y + 21, { align: 'center' });
      doc.setTextColor.apply(doc, C.muted); doc.setFont('helvetica', 'bold'); doc.setFontSize(7);
      doc.text(it.lbl.toUpperCase(), x + w / 2, y + 34, { align: 'center' });
    });
    return y + 42;
  }
  function statBlock(doc, x, y, w, title, rows) {
    doc.setTextColor.apply(doc, C.mid); doc.setFont('helvetica', 'bold'); doc.setFontSize(9);
    doc.text(title.toUpperCase(), x, y);
    doc.setDrawColor.apply(doc, C.line); doc.setLineWidth(0.5); doc.line(x, y + 3, x + w, y + 3);
    let yy = y + 16;
    doc.setFontSize(9);
    rows.forEach(([k, v]) => {
      doc.setTextColor.apply(doc, C.muted); doc.setFont('helvetica', 'normal'); doc.text(String(k), x, yy);
      doc.setTextColor.apply(doc, C.dark); doc.setFont('helvetica', 'bold'); doc.text(String(v), x + w, yy, { align: 'right' });
      yy += 13.5;
    });
    return yy;
  }
  const safe = s => String(s || 'report').replace(/[^a-z0-9]+/gi, '_').replace(/^_|_$/g, '');

  // ── Player season report ─────────────────────────────────────────
  function playerReport({ playerName, teamName, rounds }) {
    const JsPDF = ensureLib(); if (!JsPDF) return;
    rounds = rounds || [];
    const doc = new JsPDF({ unit: 'pt', format: 'letter' });
    const W = doc.internal.pageSize.getWidth();
    const s = computeSeason(rounds);
    const dates = rounds.map(r => r.round_date).filter(Boolean).sort();
    const range = dates.length ? `${dates[0]} – ${dates[dates.length - 1]}` : '';

    header(doc, 'Season Report');
    doc.setTextColor.apply(doc, C.dark); doc.setFont('helvetica', 'bold'); doc.setFontSize(19);
    doc.text(String(playerName || 'Player'), 40, 86);
    doc.setFont('helvetica', 'normal'); doc.setFontSize(10); doc.setTextColor.apply(doc, C.muted);
    doc.text([teamName, `${s.rounds} round${s.rounds === 1 ? '' : 's'}`, range].filter(Boolean).join('    •    '), 40, 102);

    let y = kpiRow(doc, 116, [
      { lbl: 'Scoring Avg', val: f1(s.scoringAvg) },
      { lbl: 'vs Par', val: vs(s.vspar) },
      { lbl: 'FW %', val: pct(s.fwPct) },
      { lbl: 'GIR %', val: pct(s.girPct) },
      { lbl: 'Putts/Rnd', val: f1(s.puttsPerRound) },
      { lbl: 'Scrambling', val: pct(s.scramblingPct) },
    ]);

    y += 24;
    const m = 40, colW = (W - 2 * m - 24) / 2, x2 = m + colW + 24;
    let ly = statBlock(doc, m, y, colW, 'Scoring', [
      ['Rounds', s.rounds],
      ['Scoring average', f1(s.scoringAvg)],
      ['Average vs par', vs(s.vspar)],
      ['Best round', s.best != null ? s.best : '—'],
      ['Birdies / Pars', `${num(s.birdies)} / ${num(s.pars)}`],
      ['Bogeys / Double+', `${num(s.bogeys)} / ${num((s.doubles || 0) + (s.worses || 0))}`],
      ['Penalty strokes', num(s.penTotal)],
    ]);
    ly = statBlock(doc, m, ly + 12, colW, 'Putting', [
      ['Putts per round', f1(s.puttsPerRound)],
      ['Putts per GIR', f1(s.puttsPerGir)],
      ['1-putts', num(s.onePutts)],
      ['3-putts', num(s.threePutts)],
    ]);
    ly = statBlock(doc, m, ly + 12, colW, 'Scrambling & Sand', [
      ['Scrambling %', pct(s.scramblingPct)],
      ['Up & downs', `${num(s.udMade)} / ${num(s.udAtt)}`],
      ['Sand save %', pct(s.ssPct)],
      ['Sand saves', `${num(s.ssMade)} / ${num(s.ssAtt)}`],
    ]);

    let ry = statBlock(doc, x2, y, colW, 'Driving', [
      ['Fairway %', pct(s.fwPct)],
      ['Fairways hit', `${num(s.fwHit)} / ${num(s.fwAtt)}`],
      ['Avg drive', s.driveAvg != null ? Math.round(s.driveAvg) + ' yds' : '—'],
      ['Longest drive', s.driveMax != null ? s.driveMax + ' yds' : '—'],
    ]);
    ry = statBlock(doc, x2, ry + 12, colW, 'Approach / GIR', [
      ['GIR %', pct(s.girPct)],
      ['Greens hit', `${num(s.girHit)} / ${num(s.girHoles)}`],
      ['Avg proximity', s.proxAvg != null ? f1(s.proxAvg) + ' ft' : '—'],
      ['Prox — on GIR', s.proxGir != null ? f1(s.proxGir) + ' ft' : '—'],
      ['Prox — missed', s.proxMiss != null ? f1(s.proxMiss) + ' ft' : '—'],
    ]);
    ry = statBlock(doc, x2, ry + 12, colW, 'By Par Type (avg / GIR)', [
      ['Par 3s', `${f1(s.par3Avg)}  /  ${pct(s.par3GirPct)}`],
      ['Par 4s', `${f1(s.par4Avg)}  /  ${pct(s.par4GirPct)}`],
      ['Par 5s', `${f1(s.par5Avg)}  /  ${pct(s.par5GirPct)}`],
    ]);

    const body = rounds.slice().sort((a, b) => (a.round_date || '').localeCompare(b.round_date || '')).map(r => {
      const su = r.summary || {};
      return [r.round_date || '—', r.course_name || '—', r.tournament || '—', r.round_num || '',
        su.totalScore != null ? su.totalScore : '—', vs(su.vspar), pct(su.fwPct), pct(su.girPct),
        su.puttsTotal != null ? su.puttsTotal : '—'];
    });
    doc.autoTable({
      startY: Math.max(ly, ry) + 20,
      head: [['Date', 'Course', 'Tournament', 'Rnd', 'Score', '+/-', 'FW%', 'GIR%', 'Putts']],
      body: body.length ? body : [[{ content: 'No rounds logged yet.', colSpan: 9, styles: { halign: 'center', textColor: C.muted } }]],
      theme: 'grid', styles: { fontSize: 8, cellPadding: 3 },
      headStyles: { fillColor: C.mid, textColor: 255, fontSize: 8 },
      columnStyles: { 1: { halign: 'left' }, 2: { halign: 'left' }, 4: { fontStyle: 'bold' } },
      margin: { left: 40, right: 40 }, didDrawPage: () => footer(doc),
    });
    doc.save(`StatCaddie_${safe(playerName)}_Season_Report.pdf`);
  }

  // ── Team report ──────────────────────────────────────────────────
  function teamReport({ teamName, players, rounds }) {
    const JsPDF = ensureLib(); if (!JsPDF) return;
    players = players || []; rounds = rounds || [];
    const doc = new JsPDF({ unit: 'pt', format: 'letter' });
    const t = computeSeason(rounds);

    header(doc, 'Team Report');
    doc.setTextColor.apply(doc, C.dark); doc.setFont('helvetica', 'bold'); doc.setFontSize(19);
    doc.text(String(teamName || 'Team'), 40, 86);
    doc.setFont('helvetica', 'normal'); doc.setFontSize(10); doc.setTextColor.apply(doc, C.muted);
    let range = '';
    try { range = new Date().toLocaleDateString(); } catch (e) {}
    doc.text([`${players.length} player${players.length === 1 ? '' : 's'}`, `${rounds.length} rounds`, range].filter(Boolean).join('    •    '), 40, 102);

    const y = kpiRow(doc, 116, [
      { lbl: 'Players', val: players.length },
      { lbl: 'Rounds', val: rounds.length },
      { lbl: 'Team Avg', val: f1(t.scoringAvg) },
      { lbl: 'vs Par', val: vs(t.vspar) },
      { lbl: 'FW %', val: pct(t.fwPct) },
      { lbl: 'GIR %', val: pct(t.girPct) },
    ]);

    const ranked = players.slice().sort((a, b) => {
      const av = a.stats.scoringAvg, bv = b.stats.scoringAvg;
      if (av == null && bv == null) return 0;
      if (av == null) return 1; if (bv == null) return -1;
      return av - bv;
    });
    const body = ranked.map((p, i) => [
      p.stats.rounds ? (i + 1) : '–',
      p.name + (p.role === 'team_admin' ? ' (Coach)' : ''),
      p.stats.rounds || '—', f1(p.stats.scoringAvg), vs(p.stats.vspar),
      pct(p.stats.fwPct), pct(p.stats.girPct), f1(p.stats.putts), pct(p.stats.scram),
    ]);
    doc.autoTable({
      startY: y + 24,
      head: [['#', 'Player', 'Rounds', 'Avg', 'vs Par', 'FW%', 'GIR%', 'Putts', 'Scr%']],
      body: body.length ? body : [[{ content: 'No players yet.', colSpan: 9, styles: { halign: 'center', textColor: C.muted } }]],
      theme: 'grid', styles: { fontSize: 9, cellPadding: 4 },
      headStyles: { fillColor: C.dark, textColor: 255 },
      columnStyles: { 1: { halign: 'left', fontStyle: 'bold' }, 3: { fontStyle: 'bold' } },
      margin: { left: 40, right: 40 }, didDrawPage: () => footer(doc),
    });
    doc.save(`StatCaddie_${safe(teamName)}_Team_Report.pdf`);
  }

  window.StatCaddiePDF = { computeSeason, playerReport, teamReport };
})();
